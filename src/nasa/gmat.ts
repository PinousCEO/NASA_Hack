/**
 * GMAT (NASA General Mission Analysis Tool) interface.
 *
 *  - `exportGmatScript`  builds a GMAT script for the mission orbit (always available).
 *  - `parseGmatReport`   turns a GMAT ReportFile into trajectory JSON, the hand-off used by
 *                        NASA's Web-based Space Mission Visualization (mission-viz) workflow.
 *  - `runGmat`           runs a real GMAT installation when `GMAT_BIN` points at one.
 *
 * GMAT is not bundled. Without it, the platform's own propagators are approximations and
 * are labelled as such; nothing here imitates GMAT output.
 */
import { execFile } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import type { MissionConfig } from "../state/schema.js";

const GMAT_BODY = { earth: "Earth", moon: "Luna", mars: "Mars" } as const;
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

/** GMAT UTCGregorian epoch: "01 Mar 2027 00:00:00.000". */
export function gmatEpoch(iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) throw new RangeError(`Invalid epoch: ${iso}`);
  const p = (n: number, w = 2): string => String(n).padStart(w, "0");
  return `${p(d.getUTCDate())} ${MONTHS[d.getUTCMonth()]} ${d.getUTCFullYear()} ${p(d.getUTCHours())}:${p(d.getUTCMinutes())}:${p(d.getUTCSeconds())}.${p(d.getUTCMilliseconds(), 3)}`;
}

export interface GmatScriptOptions {
  durationDays: number;
  /** Gravity field degree/order for the central body (2/0 = J2 only). */
  gravityDegree?: number;
  gravityOrder?: number;
  /** Include the Sun and Earth as point masses (third-body perturbations). */
  thirdBodies?: boolean;
  reportFile?: string;
  totalMassKg?: number;
}

export function exportGmatScript(config: MissionConfig, options: GmatScriptOptions): string {
  const body = GMAT_BODY[config.centralBody];
  const cs = config.centralBody === "earth" ? "EarthMJ2000Eq" : `${body}Inertial`;
  const report = options.reportFile ?? "mission_ephemeris.txt";
  const points = options.thirdBodies === false ? [] : ["Sun", ...(config.centralBody === "earth" ? ["Luna"] : ["Earth"])];
  const o = config.orbit;
  const lines = [
    "%General Mission Analysis Tool(GMAT) Script",
    `% Mission: ${config.meta.name.replace(/[\r\n%]/g, " ")}`,
    "% Generated by mission-ai-core (gmat.export_script). Review before use.",
    "",
    "Create Spacecraft Sat;",
    "GMAT Sat.DateFormat = UTCGregorian;",
    `GMAT Sat.Epoch = '${gmatEpoch(o.epoch)}';`,
    ...(config.centralBody === "earth" ? [] : [`Create CoordinateSystem ${cs};`, `GMAT ${cs}.Origin = ${body};`, `GMAT ${cs}.Axes = BodyInertial;`]),
    `GMAT Sat.CoordinateSystem = ${cs};`,
    "GMAT Sat.DisplayStateType = Keplerian;",
    `GMAT Sat.SMA = ${o.semiMajorAxisKm};`,
    `GMAT Sat.ECC = ${o.eccentricity};`,
    `GMAT Sat.INC = ${o.inclinationDeg};`,
    `GMAT Sat.RAAN = ${o.raanDeg};`,
    `GMAT Sat.AOP = ${o.argPeriapsisDeg};`,
    `GMAT Sat.TA = ${o.trueAnomalyDeg};`,
    ...(options.totalMassKg ? [`GMAT Sat.DryMass = ${options.totalMassKg.toFixed(3)};`] : []),
    "",
    "Create ForceModel FM;",
    `GMAT FM.CentralBody = ${body};`,
    `GMAT FM.PrimaryBodies = {${body}};`,
    ...(points.length ? [`GMAT FM.PointMasses = {${points.join(", ")}};`] : []),
    `GMAT FM.GravityField.${body}.Degree = ${options.gravityDegree ?? 2};`,
    `GMAT FM.GravityField.${body}.Order = ${options.gravityOrder ?? 0};`,
    "GMAT FM.Drag = None;",
    "GMAT FM.SRP = Off;",
    "",
    "Create Propagator Prop;",
    "GMAT Prop.FM = FM;",
    "GMAT Prop.Type = RungeKutta89;",
    "GMAT Prop.InitialStepSize = 60;",
    "GMAT Prop.Accuracy = 1e-11;",
    "GMAT Prop.MinStep = 0.001;",
    "GMAT Prop.MaxStep = 300;",
    "",
    "Create ReportFile Ephemeris;",
    `GMAT Ephemeris.Filename = '${report.replace(/'/g, "")}';`,
    "GMAT Ephemeris.Precision = 16;",
    "GMAT Ephemeris.WriteHeaders = true;",
    "GMAT Ephemeris.LeftJustify = On;",
    "GMAT Ephemeris.ZeroFill = Off;",
    "GMAT Ephemeris.ColumnWidth = 23;",
    `GMAT Ephemeris.Add = {Sat.ElapsedSecs, Sat.${cs}.X, Sat.${cs}.Y, Sat.${cs}.Z, Sat.${cs}.VX, Sat.${cs}.VY, Sat.${cs}.VZ};`,
    "",
    "BeginMissionSequence;",
    `Propagate Prop(Sat) {Sat.ElapsedDays = ${options.durationDays}};`,
    "",
  ];
  return lines.join("\n");
}

export interface GmatTrajectory {
  columns: string[];
  samples: { elapsedS: number; positionKm: [number, number, number]; velocityKmS: [number, number, number] }[];
}

/** Parse a GMAT ReportFile containing ElapsedSecs, X, Y, Z, VX, VY, VZ columns (in any order). */
export function parseGmatReport(text: string): GmatTrajectory {
  const lines = text.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  const headerIndex = lines.findIndex((l) => /ElapsedSecs/.test(l) && /\.X\b/.test(l));
  if (headerIndex < 0) throw new Error("Not a recognised GMAT ReportFile: expected a header with ElapsedSecs and X/Y/Z/VX/VY/VZ columns");
  const columns = lines[headerIndex]!.split(/\s+/);
  const col = (suffix: RegExp): number => {
    const i = columns.findIndex((c) => suffix.test(c));
    if (i < 0) throw new Error(`GMAT report is missing a column matching ${suffix}`);
    return i;
  };
  const idx = { t: col(/ElapsedSecs$/), x: col(/\.X$/), y: col(/\.Y$/), z: col(/\.Z$/), vx: col(/\.VX$/), vy: col(/\.VY$/), vz: col(/\.VZ$/) };
  const samples = lines.slice(headerIndex + 1).map((line, n) => {
    const cells = line.split(/\s+/).map(Number);
    if (cells.length < columns.length || cells.some((c) => !Number.isFinite(c))) throw new Error(`GMAT report row ${n + 1} is malformed`);
    return {
      elapsedS: cells[idx.t]!,
      positionKm: [cells[idx.x]!, cells[idx.y]!, cells[idx.z]!] as [number, number, number],
      velocityKmS: [cells[idx.vx]!, cells[idx.vy]!, cells[idx.vz]!] as [number, number, number],
    };
  });
  if (samples.length === 0) throw new Error("GMAT report contains no data rows");
  return { columns, samples };
}

export function gmatStatus(): { available: boolean; reason?: string; binary?: string } {
  const bin = process.env.GMAT_BIN;
  if (!bin) return { available: false, reason: "GMAT is not installed/configured: set GMAT_BIN to a GMAT console executable to enable gmat.run" };
  if (!existsSync(bin)) return { available: false, reason: `GMAT_BIN points to a file that does not exist` };
  return { available: true, binary: bin };
}

/** Run GMAT on a script and return the parsed ephemeris report. Requires a real installation. */
export async function runGmat(config: MissionConfig, options: GmatScriptOptions, signal?: AbortSignal): Promise<GmatTrajectory & { script: string }> {
  const status = gmatStatus();
  if (!status.available || !status.binary) throw new Error(status.reason);
  const dir = mkdtempSync(path.join(os.tmpdir(), "gmat-run-"));
  try {
    const reportFile = path.join(dir, "mission_ephemeris.txt").replace(/\\/g, "/");
    const script = exportGmatScript(config, { ...options, reportFile });
    const scriptFile = path.join(dir, "mission.script");
    writeFileSync(scriptFile, script);
    await new Promise<void>((resolve, reject) => {
      // Arguments are passed as an array: nothing from the mission reaches a shell.
      execFile(status.binary!, ["--run", scriptFile, "--exit"], { cwd: dir, timeout: 5 * 60 * 1000, ...(signal ? { signal } : {}), windowsHide: true }, (err) => (err ? reject(new Error(`GMAT run failed: ${err.message}`)) : resolve()));
    });
    if (!existsSync(reportFile)) throw new Error("GMAT finished without producing the ephemeris report");
    return { ...parseGmatReport(readFileSync(reportFile, "utf8")), script };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}
